// Writes LICENSES.txt: the licence text of every npm package Mermaid and KaTeX are built from.
// Run by build.sh inside the temporary install (argument: the output file).
const fs = require("fs"), path = require("path"), { execSync } = require("child_process");
const dirs = execSync("npm ls --omit=dev --all --parseable", { encoding: "utf8" }).trim().split("\n").slice(1);
let out = "Licences of Mermaid, KaTeX and the packages they are built from (the files in this folder).\nGenerated by build/build.sh from the npm packages at the versions below.\n\n";
for (const dir of [...new Set(dirs)].sort()) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const license = typeof pkg.license === "string" ? pkg.license : (pkg.license && pkg.license.type) || "see package";
  const file = fs.readdirSync(dir).find((name) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(name));
  out += `================================================================\n${pkg.name}@${pkg.version} (${license})\n================================================================\n`;
  out += file ? `${fs.readFileSync(path.join(dir, file), "utf8").trim()}\n\n` : `(no licence file in the package; licence ${license})\n\n`;
}
fs.writeFileSync(process.argv[2], out);
